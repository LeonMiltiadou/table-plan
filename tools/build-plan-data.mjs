/* Builds plan-data.js — the demo plan the app opens with.
   Run: node tools/build-plan-data.mjs

   These names are invented. Keep it that way: this file is public.
   Real guest lists belong in a .json file you keep locally and load with
   the app's "Open backup" button. */
import { writeFileSync } from "node:fs";

// Guests sit in chair order, clockwise from the top corner of the table.
const GROUPS = {
  "Top table": [
    ["Ada", "Bell"], ["Ben", "Bell"], ["Cleo", "Fox"], ["Dan", "Fox"],
    ["Elsie", "Hart"], ["Femi", "Hart"],
  ],
  Rosemary: [
    ["Greta", "Lane"], ["Hugo", "Lane"],
    ["Iris", "Moss", "vegetarian"], ["Jonah", "Moss"], ["Kit", "Nolan"],
    ["Lena", "Nolan", null, "Peanuts"],
    ["Mira", "Okafor"], ["Nils", "Okafor"], ["Omar", "Pike"], ["Pia", "Pike"],
  ],
  Juniper: [
    ["Quinn", "Reid", "vegan"], ["Rosa", "Reid"],
    ["Sam", "Shaw"], ["Tara", "Shaw"], ["Umar", "Tate"],
    ["Vera", "Tate", "pescatarian"],
    ["Will", "Vance"], ["Xena", "Vance"], ["Yuri", "Ward"], ["Zoe", "Ward"],
  ],
  Thyme: [
    ["Anya", "Bright"], ["Bo", "Bright"],
    ["Cara", "Doyle"], ["Dev", "Doyle"], ["Effie", "Ellis"],
    ["Frank", "Ellis"],
    ["Gia", "Gale"], ["Hal", "Gale"],
  ],
};

const SIDES = { ne: 2, se: 3, sw: 2, nw: 3 };

const TABLES = [
  { name: "Top table", kind: "rect",    x: 700,  y: 260,  angle: 0, seats: 6 },
  { name: "Rosemary",  kind: "diamond", x: 380,  y: 720,  angle: 0 },
  { name: "Juniper",   kind: "diamond", x: 1020, y: 720,  angle: 0 },
  // Eight guests on a ten-chair table: chairs 6 and 10 stay empty.
  { name: "Thyme",     kind: "diamond", x: 700,  y: 1160, angle: 0, gaps: [5, 9] },
];

const guests = [];
const seating = {};
const tables = [];

for (const spec of TABLES) {
  const id = "t-" + spec.name.toLowerCase().replace(/\s+/g, "-");
  const table = { id, name: spec.name, kind: spec.kind, x: spec.x, y: spec.y, angle: spec.angle };
  if (spec.kind === "rect") table.seats = spec.seats;
  else table.sides = { ...SIDES };
  tables.push(table);

  const chairs = spec.kind === "rect" ? spec.seats : Object.values(SIDES).reduce((a, b) => a + b, 0);
  const gaps = new Set(spec.gaps || []);
  const row = Array.from({ length: chairs }, () => null);

  const list = GROUPS[spec.name];
  let g = 0;
  for (let i = 0; i < chairs && g < list.length; i++) {
    if (gaps.has(i)) continue;
    const [first, last, diet = null, allergy = null] = list[g++];
    const gid = `g-${guests.length + 1}`;
    guests.push({ id: gid, first, last, diet, allergy });
    row[i] = gid;
  }
  if (g !== list.length) throw new Error(`${spec.name}: ${list.length} guests but only ${g} chairs filled`);
  seating[id] = row;
}

writeFileSync(
  new URL("../plan-data.js", import.meta.url),
  "/* Generated by tools/build-plan-data.mjs — edit that, not this. */\n" +
  "/* Demo data. Invented names only: this file is public. */\n" +
  "window.DEFAULT_PLAN = " + JSON.stringify({ name: "Example plan", guests, tables, seating }, null, 2) + ";\n"
);

console.log(`${guests.length} guests, ${tables.length} tables`);
